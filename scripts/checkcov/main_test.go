// The tests drive run() rather than main() so they assert the exact exit code
// and the exact stdout and stderr, not just "it failed". The format helpers
// below spell out the line layout independently of main.go, so a change to
// the report format fails a test instead of silently rewriting expectations.

func okLine(pkg, coverage, floor, mark string) string {
	return fmt.Sprintf("ok   %-55s coverage=%s floor=%s%s", pkg, coverage, floor, mark)
}

func skipLine(pkg, reason string) string {
	return fmt.Sprintf("skip %-55s excluded: %s", pkg, reason)
}

func failLine(message string) string {
	return "FAIL " + message
}

// failSummary is the stderr of any run that reported at least one failure.
const failSummary = "\ncheckcov: one or more per-package coverage floors were missed.\n" +
	"Fix the regression; do not lower a floor to make CI green. An\n" +
	"intentional drop updates floors.json in the same commit, with a\n" +
	"fresh measurement named in the floor's reason.\n"

func writeFile(t *testing.T, dir, name, content string) string {
	t.Helper()
	path := filepath.Join(dir, name)
	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
	return path
}

// expand substitutes the temp directory's fixed fixture names into an
// expected message, so tests never hard-code a temporary path.
func expand(s, dir string) string {
	return strings.NewReplacer(
		"{profile}", filepath.Join(dir, "coverage.out"),
		"{floors}", filepath.Join(dir, "floors.json"),
		"{packages}", filepath.Join(dir, "packages.txt"),
	).Replace(s)
}

type runCase struct {
	name string
	// args, when set, is passed to run() verbatim and the fixtures below are
	// ignored; otherwise the fixtures are written out and named on the
	// command line.
	args     []string
	profile  string
	floors   string
	packages string
	wantCode int
	wantOut  string
	wantErr  string
}

func TestRun(t *testing.T) {
	tests := []runCase{
		{
			name: "meets every floor and skips exclusions and node_modules",
			profile: "mode: atomic\n" +
				"github.com/example/mod/a.go:1.1,2.2 3 1\n" +
				"github.com/example/mod/a.go:3.3,4.4 2 0\n" +
				"github.com/example/mod/b/b.go:1.1,2.2 4 4\n" +
				"github.com/example/mod/ex/x.go:1.1,2.2 1 0\n" +
				"github.com/example/mod/node_modules/flatted/golang/pkg/flatted/f.go:1.1,2.2 10 0\n",
			floors: `{
  "note": "fixture",
  "policy": {"signing_path_floor_min_exclusive": 50, "text": "fixture policy"},
  "packages": {
    "github.com/example/mod": {"measured": 60, "floor": 55, "reason": "signing fixture", "signing_path": true},
    "github.com/example/mod/b": {"measured": 100, "floor": 100, "reason": "fully covered fixture"}
  },
  "excluded": {"github.com/example/mod/ex": "no tests by design: fixture"}
}`,
			packages: "# generated by go list\n" +
				"github.com/example/mod\n" +
				"github.com/example/mod/b\n" +
				"github.com/example/mod/ex\n" +
				"github.com/example/mod/node_modules/flatted/golang/pkg/flatted\n",
			wantCode: 0,
			wantOut: strings.Join([]string{
				okLine("github.com/example/mod", "60.00%", "55.00%", "  signing-path"),
				okLine("github.com/example/mod/b", "100.00%", "100.00%", ""),
				skipLine("github.com/example/mod/ex", "no tests by design: fixture"),
				"",
				"checkcov: 2 packages met their floors, 1 excluded",
				"",
			}, "\n"),
		},
		{
			name: "a drop fails naming the package and both numbers",
			profile: "mode: atomic\n" +
				"github.com/example/mod/a.go:1.1,2.2 3 1\n" +
				"github.com/example/mod/a.go:3.3,4.4 3 0\n",
			floors: `{
  "policy": {"signing_path_floor_min_exclusive": 50},
  "packages": {
    "github.com/example/mod": {"measured": 60, "floor": 55, "reason": "signing fixture", "signing_path": true}
  }
}`,
			packages: "github.com/example/mod\n",
			wantCode: 1,
			wantOut:  failLine("github.com/example/mod: coverage 50.00% < floor 55.00% (measured 60.00% when the floor was set)") + "\n",
			wantErr:  failSummary,
		},
		{
			name: "a signing-path floor at the policy minimum is refused",
			profile: "mode: atomic\n" +
				"github.com/example/mod/a.go:1.1,2.2 4 1\n" +
				"github.com/example/mod/a.go:3.3,4.4 1 0\n",
			floors: `{
  "policy": {"signing_path_floor_min_exclusive": 50},
  "packages": {
    "github.com/example/mod": {"measured": 80, "floor": 50, "reason": "signing fixture", "signing_path": true}
  }
}`,
			packages: "github.com/example/mod\n",
			wantCode: 1,
			wantOut:  failLine("github.com/example/mod: signing-path floor 50.00% is not strictly above the policy minimum of 50.00%") + "\n",
			wantErr:  failSummary,
		},
		{
			name: "a floor above its measurement is refused as aspiration",
			profile: "mode: atomic\n" +
				"github.com/example/mod/a.go:1.1,2.2 4 1\n" +
				"github.com/example/mod/a.go:3.3,4.4 1 0\n",
			floors: `{
  "policy": {"signing_path_floor_min_exclusive": 50},
  "packages": {
    "github.com/example/mod": {"measured": 60, "floor": 70, "reason": "raised without measuring"}
  }
}`,
			packages: "github.com/example/mod\n",
			wantCode: 1,
			wantOut:  failLine("github.com/example/mod: floor 70.00% is above the measured 60.00% it was set from (floors come from measurement, not aspiration)") + "\n",
			wantErr:  failSummary,
		},
		{
			name: "a package with no floor and no exclusion fails",
			profile: "mode: atomic\n" +
				"github.com/example/mod/a.go:1.1,2.2 4 4\n" +
				"github.com/example/mod/b/b.go:1.1,2.2 4 4\n",
			floors: `{
  "policy": {"signing_path_floor_min_exclusive": 50},
  "packages": {
    "github.com/example/mod/b": {"measured": 100, "floor": 100, "reason": "floored fixture"}
  }
}`,
			packages: "github.com/example/mod\n" +
				"github.com/example/mod/b\n",
			wantCode: 1,
			wantOut: strings.Join([]string{
				failLine("github.com/example/mod: no floor in floors.json and not listed under excluded (packages with no tests are excluded by name, never given a floor of zero)"),
				okLine("github.com/example/mod/b", "100.00%", "100.00%", ""),
				"",
			}, "\n"),
			wantErr: failSummary,
		},
		{
			name: "a floor for a package that no longer exists fails",
			profile: "mode: atomic\n" +
				"github.com/example/mod/a.go:1.1,2.2 4 4\n",
			floors: `{
  "policy": {"signing_path_floor_min_exclusive": 50},
  "packages": {
    "github.com/example/mod": {"measured": 100, "floor": 100, "reason": "floored fixture"},
    "github.com/example/mod/ghost": {"measured": 90, "floor": 80, "reason": "stale fixture"}
  }
}`,
			packages: "github.com/example/mod\n",
			wantCode: 1,
			wantOut: strings.Join([]string{
				okLine("github.com/example/mod", "100.00%", "100.00%", ""),
				failLine("github.com/example/mod/ghost: floor in floors.json but no such package in packages.txt or the coverage profile (removed or renamed; update the table)"),
				"",
			}, "\n"),
			wantErr: failSummary,
		},
		{
			name: "an exclusion for a package that no longer exists fails",
			profile: "mode: atomic\n" +
				"github.com/example/mod/a.go:1.1,2.2 4 4\n",
			floors: `{
  "policy": {"signing_path_floor_min_exclusive": 50},
  "packages": {
    "github.com/example/mod": {"measured": 100, "floor": 100, "reason": "floored fixture"}
  },
  "excluded": {"github.com/example/mod/ghost": "stale fixture"}
}`,
			packages: "github.com/example/mod\n",
			wantCode: 1,
			wantOut: strings.Join([]string{
				okLine("github.com/example/mod", "100.00%", "100.00%", ""),
				failLine("github.com/example/mod/ghost: excluded in floors.json but no such package in packages.txt or the coverage profile (removed or renamed; update the table)"),
				"",
			}, "\n"),
			wantErr: failSummary,
		},
		{
			name: "an excluded package that gained coverage fails",
			profile: "mode: atomic\n" +
				"github.com/example/mod/a.go:1.1,2.2 4 4\n" +
				"github.com/example/mod/ex/x.go:1.1,2.2 1 1\n",
			floors: `{
  "policy": {"signing_path_floor_min_exclusive": 50},
  "packages": {
    "github.com/example/mod": {"measured": 100, "floor": 100, "reason": "floored fixture"}
  },
  "excluded": {"github.com/example/mod/ex": "no tests by design: fixture"}
}`,
			packages: "github.com/example/mod\n" +
				"github.com/example/mod/ex\n",
			wantCode: 1,
			wantOut: strings.Join([]string{
				okLine("github.com/example/mod", "100.00%", "100.00%", ""),
				failLine("github.com/example/mod/ex: excluded but now measures 100.00% coverage; give it a floor or document why the exclusion still holds"),
				skipLine("github.com/example/mod/ex", "no tests by design: fixture"),
				"",
			}, "\n"),
			wantErr: failSummary,
		},
		{
			name: "a package seen only in the profile is still checked",
			profile: "mode: atomic\n" +
				"github.com/example/mod/a.go:1.1,2.2 4 4\n" +
				"github.com/example/mod/b/b.go:1.1,2.2 2 2\n",
			floors: `{
  "policy": {"signing_path_floor_min_exclusive": 50},
  "packages": {
    "github.com/example/mod": {"measured": 100, "floor": 100, "reason": "floored fixture"},
    "github.com/example/mod/b": {"measured": 50, "floor": 50, "reason": "floored fixture"}
  }
}`,
			packages: "github.com/example/mod/b\n",
			wantCode: 0,
			wantOut: strings.Join([]string{
				okLine("github.com/example/mod/b", "100.00%", "50.00%", ""),
				okLine("github.com/example/mod", "100.00%", "100.00%", ""),
				"",
				"checkcov: 2 packages met their floors, 0 excluded",
				"",
			}, "\n"),
		},
		{
			name: "a floored package with no statement counts fails",
			profile: "mode: atomic\n" +
				"github.com/example/mod/a.go:1.1,2.2 0 0\n",
			floors: `{
  "policy": {"signing_path_floor_min_exclusive": 50},
  "packages": {
    "github.com/example/mod": {"measured": 60, "floor": 55, "reason": "floored fixture"}
  }
}`,
			packages: "github.com/example/mod\n",
			wantCode: 1,
			wantOut:  failLine("github.com/example/mod: no statement counts in the coverage profile") + "\n",
			wantErr:  failSummary,
		},
		{
			name:     "no arguments is a usage error",
			args:     []string{"checkcov"},
			wantCode: 2,
			wantErr:  "usage: checkcov <coverage.out> <floors.json> <packages.txt>\n",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dir := t.TempDir()
			args := tt.args
			if args == nil {
				args = []string{"checkcov",
					writeFile(t, dir, "coverage.out", tt.profile),
					writeFile(t, dir, "floors.json", tt.floors),
					writeFile(t, dir, "packages.txt", tt.packages),
				}
			}
			var stdout, stderr bytes.Buffer
			code := run(args, &stdout, &stderr)
			if code != tt.wantCode {
				t.Errorf("exit code = %d, want %d\nstdout:\n%s\nstderr:\n%s", code, tt.wantCode, stdout.String(), stderr.String())
			}
			if got := stdout.String(); got != expand(tt.wantOut, dir) {
				t.Errorf("stdout:\n%s\nwant:\n%s", got, expand(tt.wantOut, dir))
			}
			if got := stderr.String(); got != expand(tt.wantErr, dir) {
				t.Errorf("stderr:\n%s\nwant:\n%s", got, expand(tt.wantErr, dir))
			}
		})
	}
}

func TestRunParseErrors(t *testing.T) {
	const goodProfile = "mode: atomic\ngithub.com/example/mod/a.go:1.1,2.2 4 4\n"
	const goodPackages = "github.com/example/mod\n"
	const goodFloors = `{
  "policy": {"signing_path_floor_min_exclusive": 50},
  "packages": {"github.com/example/mod": {"measured": 100, "floor": 100, "reason": "fixture"}}
}`

	tests := []struct {
		name     string
		profile  string
		floors   string
		packages string
		wantErr  string
	}{
		{
			name:     "profile without a mode line",
			profile:  "github.com/example/mod/a.go:1.1,2.2 4 4\n",
			floors:   goodFloors,
			packages: goodPackages,
			wantErr:  `checkcov: {profile}: missing mode line (want "mode: set", "mode: count" or "mode: atomic")` + "\n",
		},
		{
			name:     "profile with an unknown mode",
			profile:  "mode: quadratic\n",
			floors:   goodFloors,
			packages: goodPackages,
			wantErr:  `checkcov: {profile}: unknown coverage mode "quadratic" (want set, count or atomic)` + "\n",
		},
		{
			name:     "profile with a malformed line",
			profile:  "mode: atomic\nthis is not a profile line\n",
			floors:   goodFloors,
			packages: goodPackages,
			wantErr:  `checkcov: {profile}:2: cannot parse coverage line "this is not a profile line"` + "\n",
		},
		{
			name:     "profile with only a mode line",
			profile:  "mode: atomic\n",
			floors:   goodFloors,
			packages: goodPackages,
			wantErr:  "checkcov: {profile}: no coverage lines found (is the profile empty?)\n",
		},
		{
			name:     "profile line without a package directory",
			profile:  "mode: atomic\na.go:1.1,2.2 4 4\n",
			floors:   goodFloors,
			packages: goodPackages,
			wantErr:  `checkcov: {profile}:2: cannot determine a package directory from file "a.go"` + "\n",
		},
		{
			name:     "floors without packages",
			profile:  goodProfile,
			floors:   `{"policy": {"signing_path_floor_min_exclusive": 50}}`,
			packages: goodPackages,
			wantErr:  "checkcov: {floors} has no per-package floors\n",
		},
		{
			name:     "floors with a missing signing-path policy minimum",
			profile:  goodProfile,
			floors:   `{"policy": {}, "packages": {"github.com/example/mod": {"measured": 100, "floor": 100, "reason": "fixture"}}}`,
			packages: goodPackages,
			wantErr:  "checkcov: {floors}: policy.signing_path_floor_min_exclusive must be greater than 0\n",
		},
		{
			name:     "floor without a reason",
			profile:  goodProfile,
			floors:   `{"policy": {"signing_path_floor_min_exclusive": 50}, "packages": {"github.com/example/mod": {"measured": 100, "floor": 100}}}`,
			packages: goodPackages,
			wantErr:  "checkcov: {floors}: floor for github.com/example/mod has no reason\n",
		},
		{
			name:     "exclusion without a reason",
			profile:  goodProfile,
			floors:   `{"policy": {"signing_path_floor_min_exclusive": 50}, "packages": {"github.com/example/mod": {"measured": 100, "floor": 100, "reason": "fixture"}}, "excluded": {"github.com/example/mod/ex": ""}}`,
			packages: goodPackages,
			wantErr:  "checkcov: {floors}: exclusion for github.com/example/mod/ex has no reason\n",
		},
		{
			name:     "package both floored and excluded",
			profile:  goodProfile,
			floors:   `{"policy": {"signing_path_floor_min_exclusive": 50}, "packages": {"github.com/example/mod": {"measured": 100, "floor": 100, "reason": "fixture"}}, "excluded": {"github.com/example/mod": "fixture"}}`,
			packages: goodPackages,
			wantErr:  "checkcov: {floors}: github.com/example/mod is both floored and excluded\n",
		},
		{
			name:     "packages file with no packages",
			profile:  goodProfile,
			floors:   goodFloors,
			packages: "\n# only a comment\n",
			wantErr:  "checkcov: {packages} lists no packages\n",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dir := t.TempDir()
			args := []string{"checkcov",
				writeFile(t, dir, "coverage.out", tt.profile),
				writeFile(t, dir, "floors.json", tt.floors),
				writeFile(t, dir, "packages.txt", tt.packages),
			}
			var stdout, stderr bytes.Buffer
			code := run(args, &stdout, &stderr)
			if code != 2 {
				t.Errorf("exit code = %d, want 2\nstdout:\n%s\nstderr:\n%s", code, stdout.String(), stderr.String())
			}
			if got := stderr.String(); got != expand(tt.wantErr, dir) {
				t.Errorf("stderr:\n%s\nwant:\n%s", got, expand(tt.wantErr, dir))
			}
		})
	}
}

func TestParseProfile(t *testing.T) {
	tests := []struct {
		name    string
		profile string
		want    map[string]coverage
		// wantErr is a format string; %s is the profile path.
		wantErr string
	}{
		{
			name: "aggregates files into their package directory and filters node_modules",
			profile: "mode: atomic\n" +
				"github.com/example/mod/a.go:1.1,2.2 3 1\n" +
				"github.com/example/mod/a.go:3.3,4.4 2 0\n" +
				"github.com/example/mod/b/b.go:1.1,2.2 4 0\n" +
				"github.com/example/mod/b/ignored.go:1.1,2.2 5 5\n" +
				"github.com/example/mod/node_modules/flatted/golang/pkg/flatted/f.go:1.1,2.2 10 10\n",
			want: map[string]coverage{
				"github.com/example/mod":   {covered: 3, total: 5},
				"github.com/example/mod/b": {covered: 5, total: 9},
			},
		},
		{
			name:    "accepts set mode",
			profile: "mode: set\ngithub.com/example/mod/a.go:1.1,2.2 1 1\n",
			want:    map[string]coverage{"github.com/example/mod": {covered: 1, total: 1}},
		},
		{
			name:    "accepts count mode",
			profile: "mode: count\ngithub.com/example/mod/a.go:1.1,2.2 1 1\n",
			want:    map[string]coverage{"github.com/example/mod": {covered: 1, total: 1}},
		},
		{
			name:    "tolerates CRLF line endings",
			profile: "mode: atomic\r\ngithub.com/example/mod/a.go:1.1,2.2 1 1\r\n",
			want:    map[string]coverage{"github.com/example/mod": {covered: 1, total: 1}},
		},
		{
			name:    "missing mode line",
			profile: "github.com/example/mod/a.go:1.1,2.2 1 1\n",
			wantErr: `%s: missing mode line (want "mode: set", "mode: count" or "mode: atomic")`,
		},
		{
			name:    "unknown mode",
			profile: "mode: mostly\n",
			wantErr: `%s: unknown coverage mode "mostly" (want set, count or atomic)`,
		},
		{
			name:    "malformed statement block",
			profile: "mode: atomic\ngithub.com/example/mod/a.go:1.1,2.2 1\n",
			wantErr: `%s:2: cannot parse coverage line "github.com/example/mod/a.go:1.1,2.2 1"`,
		},
		{
			name:    "statement count overflows an int",
			profile: "mode: atomic\ngithub.com/example/mod/a.go:1.1,2.2 999999999999999999999999999999 1\n",
			wantErr: `%s:2: parsing statement count in "github.com/example/mod/a.go:1.1,2.2 999999999999999999999999999999 1": strconv.Atoi: parsing "999999999999999999999999999999": value out of range`,
		},
		{
			name:    "execution count overflows an int",
			profile: "mode: atomic\ngithub.com/example/mod/a.go:1.1,2.2 1 999999999999999999999999999999\n",
			wantErr: `%s:2: parsing execution count in "github.com/example/mod/a.go:1.1,2.2 1 999999999999999999999999999999": strconv.Atoi: parsing "999999999999999999999999999999": value out of range`,
		},
		{
			name:    "file without a package directory",
			profile: "mode: atomic\na.go:1.1,2.2 1 1\n",
			wantErr: `%s:2: cannot determine a package directory from file "a.go"`,
		},
		{
			name:    "empty profile",
			profile: "mode: atomic\n",
			wantErr: "%s: no coverage lines found (is the profile empty?)",
		},
		{
			name:    "only ignored packages",
			profile: "mode: atomic\ngithub.com/example/mod/node_modules/flatted/golang/pkg/flatted/f.go:1.1,2.2 10 10\n",
			wantErr: "%s: no coverage lines found (is the profile empty?)",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			path := writeFile(t, t.TempDir(), "coverage.out", tt.profile)
			got, err := parseProfile(path)
			if tt.wantErr != "" {
				if err == nil {
					t.Fatalf("parseProfile() = %v, want error %q", got, fmt.Sprintf(tt.wantErr, path))
				}
				if want := fmt.Sprintf(tt.wantErr, path); err.Error() != want {
					t.Errorf("error = %q, want %q", err, want)
				}
				return
			}
			if err != nil {
				t.Fatalf("parseProfile() error = %v", err)
			}
			if !reflect.DeepEqual(got, tt.want) {
				t.Errorf("parseProfile() = %v, want %v", got, tt.want)
			}
		})
	}
}

