// Replay every golden vector through an *installed* @soroauth/node tarball.
//
// The in-repo test (test/vectors.test.mjs) loads the binding next to it and
// reads testdata/vectors from the checkout. That proves the source tree, not
// the package a consumer downloads. This script is the consumer's view: it is
// pointed at a directory where @soroauth/node was installed from a packed
// tarball, resolves the package from there, and compares the same three byte
// strings -- preimage, payload and final signed entry -- for every vector.
//
// It is what makes "npm install with no Go toolchain, then replay the vectors"
// a check rather than a claim: the process cannot see a Go toolchain or the
// repository's build scripts, only the tarball's own prebuilds/.
//
// Usage:
//   node scripts/smoke-installed.mjs [--vectors DIR] [--from DIR]
//
// --from is the directory whose node_modules holds the installed package
// (default: the current working directory). --vectors defaults to the checkout's
// testdata/vectors relative to this script.

import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readdirSync, readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const PACKAGE_ROOT = resolve(HERE, "..");
const REPO_ROOT = resolve(PACKAGE_ROOT, "..", "..");

/** referenceSDK is the only generator version a vector may come from. */
const referenceSDK = "@stellar/stellar-sdk@17.1.0";

function parseArgs(argv) {
  const options = {
    vectors: join(REPO_ROOT, "testdata", "vectors"),
    from: process.cwd(),
  };
  for (let index = 0; index < argv.length; index += 2) {
    const flag = argv[index];
    const value = argv[index + 1];
    if (value === undefined) {
      console.error(`smoke-installed: ${flag} needs a value`);
      process.exit(2);
    }
    if (flag === "--vectors") options.vectors = value;
    else if (flag === "--from") options.from = value;
    else {
      console.error(`smoke-installed: unknown argument ${flag}`);
      process.exit(2);
    }
  }
  return { vectors: resolve(options.vectors), from: resolve(options.from) };
}

/** seedHex is the raw seed the vector generator derives from a signer label. */
function seedHex(label) {
  return createHash("sha256").update(label).digest("hex");
}

function runSteps(soroauth, vector) {
  let entry = vector.unsigned_entry_xdr;
  for (const step of vector.steps) {
    const forAddress = step.for_address ?? "";
    entry = step.multisig
      ? soroauth.authorizeWithSeeds(
          entry,
          vector.valid_until_ledger,
          vector.network_passphrase,
          step.multisig.signer_labels.map(seedHex).join(","),
          forAddress,
        )
      : soroauth.authorizeWithSeed(
          entry,
          vector.valid_until_ledger,
          vector.network_passphrase,
          seedHex(step.signer_label),
          forAddress,
        );
  }
  return entry;
}

const options = parseArgs(process.argv.slice(2));
const requireFromInstalledProject = createRequire(join(options.from, "package.json"));

let packagePath;
try {
  packagePath = requireFromInstalledProject.resolve("@soroauth/node");
} catch (error) {
  console.error(
    `smoke-installed: @soroauth/node is not installed under ${options.from}: ${error.message}`,
  );
  process.exit(1);
}
const soroauthModule = requireFromInstalledProject("@soroauth/node");
const soroauth = soroauthModule.load();

const names = readdirSync(options.vectors)
  .filter((name) => name.endsWith(".json"))
  .sort();
assert.ok(names.length > 0, `no vectors found in ${options.vectors}`);

let signed = 0;
let sourceAccount = 0;
for (const name of names) {
  const vector = JSON.parse(readFileSync(join(options.vectors, name), "utf8"));
  assert.equal(
    vector.sdk,
    referenceSDK,
    `${name} was generated by ${vector.sdk}, want ${referenceSDK}`,
  );
  assert.equal(vector.schema_version, 1, `${name} has an unknown schema version`);

  const info = soroauth.inspect(vector.unsigned_entry_xdr);
  if (info.credential_type === "source_account") {
    assert.throws(
      () =>
        soroauth.preimage(
          vector.unsigned_entry_xdr,
          vector.valid_until_ledger,
          vector.network_passphrase,
        ),
      (error) => {
        assert.ok(
          error instanceof soroauthModule.SourceAccountCredentials,
          `${name}: ${error}`,
        );
        return true;
      },
      `${name}: preimage should refuse a source-account entry`,
    );
    assert.equal(
      soroauth.authorizeWithSeed(
        vector.unsigned_entry_xdr,
        vector.valid_until_ledger,
        vector.network_passphrase,
        seedHex("soroauth-vector-signer-1"),
        "",
      ),
      vector.signed_entry_xdr,
      `${name}: a source-account entry must pass through unchanged`,
    );
    sourceAccount += 1;
    continue;
  }

  const { preimageXdr, payloadHex } = soroauth.preimage(
    vector.unsigned_entry_xdr,
    vector.valid_until_ledger,
    vector.network_passphrase,
  );
  assert.equal(preimageXdr, vector.preimage_xdr, `${name}: preimage differs`);
  assert.equal(payloadHex, vector.payload_hex, `${name}: payload differs`);
  assert.equal(
    runSteps(soroauth, vector),
    vector.signed_entry_xdr,
    `${name}: the signed entry differs`,
  );
  signed += 1;
}

console.log(
  `smoke-installed: ${soroauth.version()} at ${packagePath} replayed ` +
    `${signed + sourceAccount} vectors (${signed} signed, ${sourceAccount} source-account)`,
);
